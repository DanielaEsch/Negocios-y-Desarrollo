-- Esquema del sistema de control de rutinas.
-- Fuente de verdad del modelo: Hibernate corre con ddl-auto: none.
--
-- Convenciones:
--   Tablas en MAYUSCULAS y singular.
--   Prefijos de columna: PK_ llave primaria, FK_ llave foranea, TX_ texto,
--   DN_ numerico o booleano, DD_ fecha.
--   Todas las tablas llevan auditoria y borrado logico (DN_ACTIVO).
--   La unicidad se aplica solo a registros activos (indice parcial).

CREATE TABLE IF NOT EXISTS AREA (
    PK_ID                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    TX_NOMBRE               VARCHAR(100) NOT NULL,
    TX_DESCRIPCION          VARCHAR(250),
    DN_USUARIO_CREADOR      BIGINT       NOT NULL,
    DD_FECHA_CREACION       TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    DN_USUARIO_MODIFICADOR  BIGINT,
    DD_FECHA_MODIFICACION   TIMESTAMP,
    DN_ACTIVO               BOOLEAN      NOT NULL DEFAULT TRUE
);

CREATE UNIQUE INDEX IF NOT EXISTS UQ_AREA_NOMBRE ON AREA (TX_NOMBRE) WHERE DN_ACTIVO;

-- Usuarios. Cumplimiento LFPDPPP: la contrasena se guarda solo como hash BCrypt
-- y no hay consentimiento sin fecha de consentimiento.
CREATE TABLE IF NOT EXISTS USUARIO (
    PK_ID                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    TX_NOMBRE               VARCHAR(150) NOT NULL,
    TX_CORREO               VARCHAR(150) NOT NULL,
    TX_HASH_CONTRASENA      VARCHAR(100) NOT NULL,
    TX_PERFIL               VARCHAR(20)  NOT NULL DEFAULT 'OPERADOR',
    DN_CONSENTIMIENTO_DATOS BOOLEAN      NOT NULL DEFAULT FALSE,
    DD_FECHA_CONSENTIMIENTO TIMESTAMP,
    DN_USUARIO_CREADOR      BIGINT       NOT NULL,
    DD_FECHA_CREACION       TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    DN_USUARIO_MODIFICADOR  BIGINT,
    DD_FECHA_MODIFICACION   TIMESTAMP,
    DN_ACTIVO               BOOLEAN      NOT NULL DEFAULT TRUE,
    CONSTRAINT CK_USUARIO_PERFIL CHECK (TX_PERFIL IN ('OPERADOR', 'SUPERVISOR', 'ADMINISTRADOR', 'COBRANZA')),
    CONSTRAINT CK_USUARIO_CONSENTIMIENTO CHECK (NOT DN_CONSENTIMIENTO_DATOS OR DD_FECHA_CONSENTIMIENTO IS NOT NULL)
);

CREATE UNIQUE INDEX IF NOT EXISTS UQ_USUARIO_CORREO ON USUARIO (TX_CORREO) WHERE DN_ACTIVO;

-- Areas a cargo de cada usuario: el operador ve las rondas de sus areas y el
-- supervisor revisa las incidencias de sus areas.
CREATE TABLE IF NOT EXISTS USUARIO_AREA (
    PK_ID                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    FK_USUARIO              BIGINT       NOT NULL,
    FK_AREA                 BIGINT       NOT NULL,
    DN_USUARIO_CREADOR      BIGINT       NOT NULL,
    DD_FECHA_CREACION       TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    DN_USUARIO_MODIFICADOR  BIGINT,
    DD_FECHA_MODIFICACION   TIMESTAMP,
    DN_ACTIVO               BOOLEAN      NOT NULL DEFAULT TRUE,
    CONSTRAINT FK_USUARIO_AREA_USUARIO FOREIGN KEY (FK_USUARIO) REFERENCES USUARIO (PK_ID) ON DELETE RESTRICT,
    CONSTRAINT FK_USUARIO_AREA_AREA FOREIGN KEY (FK_AREA) REFERENCES AREA (PK_ID) ON DELETE RESTRICT
);

CREATE UNIQUE INDEX IF NOT EXISTS UQ_USUARIO_AREA ON USUARIO_AREA (FK_USUARIO, FK_AREA) WHERE DN_ACTIVO;

-- Rutina: que hay que hacer, en que area y cada cuando. Las columnas de horario
-- que use dependen de la frecuencia (ver la estrategia de cada una en el dominio).
CREATE TABLE IF NOT EXISTS RUTINA (
    PK_ID                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    FK_AREA                 BIGINT       NOT NULL,
    TX_NOMBRE               VARCHAR(100) NOT NULL,
    TX_DESCRIPCION          VARCHAR(250),
    TX_FRECUENCIA           VARCHAR(20)  NOT NULL,
    DD_HORA_INICIO          TIME,
    DD_HORA_FIN             TIME,
    DN_DIA_SEMANA           SMALLINT,
    DN_USUARIO_CREADOR      BIGINT       NOT NULL,
    DD_FECHA_CREACION       TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    DN_USUARIO_MODIFICADOR  BIGINT,
    DD_FECHA_MODIFICACION   TIMESTAMP,
    DN_ACTIVO               BOOLEAN      NOT NULL DEFAULT TRUE,
    CONSTRAINT FK_RUTINA_AREA FOREIGN KEY (FK_AREA) REFERENCES AREA (PK_ID) ON DELETE RESTRICT,
    CONSTRAINT CK_RUTINA_FRECUENCIA CHECK (TX_FRECUENCIA IN ('CADA_2_HORAS', 'DIARIA', 'SEMANAL', 'POR_EVENTO')),
    CONSTRAINT CK_RUTINA_DIA_SEMANA CHECK (DN_DIA_SEMANA IS NULL OR DN_DIA_SEMANA BETWEEN 1 AND 7)
);

CREATE UNIQUE INDEX IF NOT EXISTS UQ_RUTINA_NOMBRE ON RUTINA (FK_AREA, TX_NOMBRE) WHERE DN_ACTIVO;

-- Pasos de una rutina, en el orden en que se hacen.
CREATE TABLE IF NOT EXISTS TAREA (
    PK_ID                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    FK_RUTINA               BIGINT       NOT NULL,
    TX_NOMBRE               VARCHAR(150) NOT NULL,
    DN_ORDEN                INTEGER      NOT NULL,
    DN_USUARIO_CREADOR      BIGINT       NOT NULL,
    DD_FECHA_CREACION       TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    DN_USUARIO_MODIFICADOR  BIGINT,
    DD_FECHA_MODIFICACION   TIMESTAMP,
    DN_ACTIVO               BOOLEAN      NOT NULL DEFAULT TRUE,
    CONSTRAINT FK_TAREA_RUTINA FOREIGN KEY (FK_RUTINA) REFERENCES RUTINA (PK_ID) ON DELETE RESTRICT
);

-- Una ocurrencia concreta de una rutina ("revision de banos de las 14:00").
-- DN_VERSION es el bloqueo optimista: dos operadores no pueden tomar la misma.
CREATE TABLE IF NOT EXISTS EJECUCION (
    PK_ID                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    FK_RUTINA               BIGINT       NOT NULL,
    DD_FECHA_PROGRAMADA     TIMESTAMP    NOT NULL,
    TX_ESTADO               VARCHAR(20)  NOT NULL DEFAULT 'PROGRAMADA',
    FK_OPERADOR             BIGINT,
    DD_FECHA_INICIO         TIMESTAMP,
    DD_FECHA_FIN            TIMESTAMP,
    DN_VERSION              BIGINT       NOT NULL DEFAULT 0,
    DN_USUARIO_CREADOR      BIGINT       NOT NULL,
    DD_FECHA_CREACION       TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    DN_USUARIO_MODIFICADOR  BIGINT,
    DD_FECHA_MODIFICACION   TIMESTAMP,
    DN_ACTIVO               BOOLEAN      NOT NULL DEFAULT TRUE,
    CONSTRAINT FK_EJECUCION_RUTINA FOREIGN KEY (FK_RUTINA) REFERENCES RUTINA (PK_ID) ON DELETE RESTRICT,
    CONSTRAINT FK_EJECUCION_OPERADOR FOREIGN KEY (FK_OPERADOR) REFERENCES USUARIO (PK_ID) ON DELETE RESTRICT,
    CONSTRAINT CK_EJECUCION_ESTADO CHECK (TX_ESTADO IN ('PROGRAMADA', 'EN_CURSO', 'COMPLETADA', 'CANCELADA', 'VENCIDA'))
);

-- La programacion es idempotente: una rutina no se programa dos veces a la misma hora.
CREATE UNIQUE INDEX IF NOT EXISTS UQ_EJECUCION_HORARIO ON EJECUCION (FK_RUTINA, DD_FECHA_PROGRAMADA) WHERE DN_ACTIVO;
CREATE INDEX IF NOT EXISTS IX_EJECUCION_FECHA ON EJECUCION (DD_FECHA_PROGRAMADA);

-- Avance de cada tarea dentro de una ejecucion.
CREATE TABLE IF NOT EXISTS TAREA_EJECUCION (
    PK_ID                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    FK_EJECUCION            BIGINT       NOT NULL,
    FK_TAREA                BIGINT       NOT NULL,
    TX_ESTADO               VARCHAR(20)  NOT NULL DEFAULT 'PENDIENTE',
    DD_FECHA_COMPLETADA     TIMESTAMP,
    DN_USUARIO_CREADOR      BIGINT       NOT NULL,
    DD_FECHA_CREACION       TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    DN_USUARIO_MODIFICADOR  BIGINT,
    DD_FECHA_MODIFICACION   TIMESTAMP,
    DN_ACTIVO               BOOLEAN      NOT NULL DEFAULT TRUE,
    CONSTRAINT FK_TAREA_EJECUCION_EJECUCION FOREIGN KEY (FK_EJECUCION) REFERENCES EJECUCION (PK_ID) ON DELETE RESTRICT,
    CONSTRAINT FK_TAREA_EJECUCION_TAREA FOREIGN KEY (FK_TAREA) REFERENCES TAREA (PK_ID) ON DELETE RESTRICT,
    CONSTRAINT CK_TAREA_EJECUCION_ESTADO CHECK (TX_ESTADO IN ('PENDIENTE', 'EN_PROCESO', 'COMPLETADA'))
);

-- Algo que salio mal durante una ejecucion. No se cierra sin comentario de resolucion.
CREATE TABLE IF NOT EXISTS INCIDENCIA (
    PK_ID                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    FK_EJECUCION             BIGINT       NOT NULL,
    FK_USUARIO_REPORTA       BIGINT       NOT NULL,
    TX_DESCRIPCION           VARCHAR(500) NOT NULL,
    TX_ESTADO                VARCHAR(20)  NOT NULL DEFAULT 'PENDIENTE',
    DD_FECHA_REPORTE         TIMESTAMP    NOT NULL,
    FK_USUARIO_REVISOR       BIGINT,
    TX_COMENTARIO_RESOLUCION VARCHAR(500),
    DD_FECHA_RESOLUCION      TIMESTAMP,
    DN_USUARIO_CREADOR       BIGINT       NOT NULL,
    DD_FECHA_CREACION        TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    DN_USUARIO_MODIFICADOR   BIGINT,
    DD_FECHA_MODIFICACION    TIMESTAMP,
    DN_ACTIVO                BOOLEAN      NOT NULL DEFAULT TRUE,
    CONSTRAINT FK_INCIDENCIA_EJECUCION FOREIGN KEY (FK_EJECUCION) REFERENCES EJECUCION (PK_ID) ON DELETE RESTRICT,
    CONSTRAINT FK_INCIDENCIA_REPORTA FOREIGN KEY (FK_USUARIO_REPORTA) REFERENCES USUARIO (PK_ID) ON DELETE RESTRICT,
    CONSTRAINT FK_INCIDENCIA_REVISOR FOREIGN KEY (FK_USUARIO_REVISOR) REFERENCES USUARIO (PK_ID) ON DELETE RESTRICT,
    CONSTRAINT CK_INCIDENCIA_ESTADO CHECK (TX_ESTADO IN ('PENDIENTE', 'REVISION', 'RESUELTA')),
    CONSTRAINT CK_INCIDENCIA_RESOLUCION CHECK (TX_ESTADO <> 'RESUELTA' OR TX_COMENTARIO_RESOLUCION IS NOT NULL)
);

-- ---------------------------------------------------------------------------
-- Evidencias: fotos que el operador adjunta a una ronda. El archivo vive fuera
-- de la base (almacenamiento de archivos); aqui solo la llave y los metadatos.
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS EVIDENCIA (
    PK_ID                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    FK_EJECUCION           BIGINT       NOT NULL,
    FK_USUARIO_SUBE        BIGINT       NOT NULL,
    TX_TIPO_CONTENIDO      VARCHAR(30)  NOT NULL,
    DN_TAMANO_BYTES        BIGINT       NOT NULL,
    TX_LLAVE_ALMACEN       VARCHAR(200) NOT NULL,
    TX_NOTA                VARCHAR(200),
    DD_FECHA_CAPTURA       TIMESTAMP    NOT NULL,
    DN_USUARIO_CREADOR     BIGINT       NOT NULL,
    DD_FECHA_CREACION      TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    DN_USUARIO_MODIFICADOR BIGINT,
    DD_FECHA_MODIFICACION  TIMESTAMP,
    DN_ACTIVO              BOOLEAN      NOT NULL DEFAULT TRUE,
    CONSTRAINT FK_EVIDENCIA_EJECUCION FOREIGN KEY (FK_EJECUCION) REFERENCES EJECUCION (PK_ID) ON DELETE RESTRICT,
    CONSTRAINT FK_EVIDENCIA_USUARIO FOREIGN KEY (FK_USUARIO_SUBE) REFERENCES USUARIO (PK_ID) ON DELETE RESTRICT,
    CONSTRAINT CK_EVIDENCIA_TIPO CHECK (TX_TIPO_CONTENIDO IN ('image/jpeg', 'image/png', 'image/webp')),
    CONSTRAINT CK_EVIDENCIA_TAMANO CHECK (DN_TAMANO_BYTES > 0 AND DN_TAMANO_BYTES <= 5242880)
);
CREATE INDEX IF NOT EXISTS IX_EVIDENCIA_EJECUCION ON EVIDENCIA (FK_EJECUCION) WHERE DN_ACTIVO;

-- ---------------------------------------------------------------------------
-- Monetizacion (ADR-002): planes, suscripcion, ordenes de pago, webhooks y CFDI.
-- El precio lo dicta el servidor: la orden guarda las entradas del calculo
-- (precio, periodo, cupon, credito) y el desglose resultante.
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS PLAN_SUSCRIPCION (
    PK_ID                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    TX_CLAVE               VARCHAR(20)   NOT NULL,
    TX_NOMBRE              VARCHAR(60)   NOT NULL,
    TX_DESCRIPCION         VARCHAR(300)  NOT NULL,
    DN_PRECIO_MENSUAL      NUMERIC(10,2) NOT NULL,
    DN_ORDEN               INTEGER       NOT NULL,
    DN_USUARIO_CREADOR     BIGINT        NOT NULL,
    DD_FECHA_CREACION      TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    DN_USUARIO_MODIFICADOR BIGINT,
    DD_FECHA_MODIFICACION  TIMESTAMP,
    DN_ACTIVO              BOOLEAN       NOT NULL DEFAULT TRUE,
    CONSTRAINT CK_PLAN_PRECIO CHECK (DN_PRECIO_MENSUAL > 0)
);
CREATE UNIQUE INDEX IF NOT EXISTS UX_PLAN_CLAVE ON PLAN_SUSCRIPCION (TX_CLAVE) WHERE DN_ACTIVO;

-- Una instalacion = un negocio, asi que hay una sola suscripcion activa.
-- VENCIDA no se guarda: se deriva de DD_VIGENCIA_FIN.
CREATE TABLE IF NOT EXISTS SUSCRIPCION (
    PK_ID                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    FK_PLAN                BIGINT       NOT NULL,
    TX_ESTADO              VARCHAR(20)  NOT NULL,
    DD_FECHA_INICIO        DATE         NOT NULL,
    DD_VIGENCIA_FIN        DATE         NOT NULL,
    TX_RFC                 VARCHAR(13),
    TX_RAZON_SOCIAL        VARCHAR(300),
    TX_CODIGO_POSTAL       VARCHAR(5),
    TX_REGIMEN_FISCAL      VARCHAR(3),
    TX_USO_CFDI            VARCHAR(4),
    DN_VERSION             BIGINT       NOT NULL DEFAULT 0,
    DN_USUARIO_CREADOR     BIGINT       NOT NULL,
    DD_FECHA_CREACION      TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    DN_USUARIO_MODIFICADOR BIGINT,
    DD_FECHA_MODIFICACION  TIMESTAMP,
    DN_ACTIVO              BOOLEAN      NOT NULL DEFAULT TRUE,
    CONSTRAINT FK_SUSCRIPCION_PLAN FOREIGN KEY (FK_PLAN) REFERENCES PLAN_SUSCRIPCION (PK_ID) ON DELETE RESTRICT,
    CONSTRAINT CK_SUSCRIPCION_ESTADO CHECK (TX_ESTADO IN ('PRUEBA', 'ACTIVA')),
    CONSTRAINT CK_SUSCRIPCION_FECHAS CHECK (DD_VIGENCIA_FIN >= DD_FECHA_INICIO)
);

-- Maquina de estados: PENDIENTE_PAGO -> PROCESANDO -> PAGADO | RECHAZADO; PENDIENTE_PAGO -> VENCIDO.
-- De la tarjeta solo se guardan marca y ultimos 4 (PCI-DSS: el numero nunca llega a TaskIn).
CREATE TABLE IF NOT EXISTS ORDEN_PAGO (
    PK_ID                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    TX_FOLIO               VARCHAR(20)   NOT NULL,
    FK_SUSCRIPCION         BIGINT        NOT NULL,
    FK_PLAN                BIGINT        NOT NULL,
    FK_USUARIO_SOLICITA    BIGINT        NOT NULL,
    TX_PERIODO             VARCHAR(10)   NOT NULL,
    TX_METODO              VARCHAR(15)   NOT NULL,
    DN_PRECIO_MENSUAL      NUMERIC(10,2) NOT NULL,
    TX_CUPON               VARCHAR(20),
    DN_PORCENTAJE_CUPON    INTEGER       NOT NULL DEFAULT 0,
    DN_CREDITO             NUMERIC(10,2) NOT NULL DEFAULT 0,
    DN_SUBTOTAL            NUMERIC(10,2) NOT NULL,
    DN_DESCUENTO           NUMERIC(10,2) NOT NULL,
    DN_IVA                 NUMERIC(10,2) NOT NULL,
    DN_TOTAL               NUMERIC(10,2) NOT NULL,
    TX_MONEDA              VARCHAR(3)    NOT NULL DEFAULT 'MXN',
    TX_ESTADO              VARCHAR(20)   NOT NULL,
    DD_FECHA_ORDEN         TIMESTAMP     NOT NULL,
    DD_FECHA_EXPIRACION    TIMESTAMP     NOT NULL,
    TX_REFERENCIA_PAGO     VARCHAR(60),
    TX_TARJETA_MARCA       VARCHAR(20),
    TX_TARJETA_ULTIMOS4    VARCHAR(4),
    TX_MOTIVO_RECHAZO      VARCHAR(300),
    FK_USUARIO_VALIDA      BIGINT,
    DD_FECHA_PAGO          TIMESTAMP,
    TX_RFC                 VARCHAR(13)   NOT NULL,
    TX_RAZON_SOCIAL        VARCHAR(300)  NOT NULL,
    TX_CODIGO_POSTAL       VARCHAR(5)    NOT NULL,
    TX_REGIMEN_FISCAL      VARCHAR(3)    NOT NULL,
    TX_USO_CFDI            VARCHAR(4)    NOT NULL,
    DN_VERSION             BIGINT        NOT NULL DEFAULT 0,
    DN_USUARIO_CREADOR     BIGINT        NOT NULL,
    DD_FECHA_CREACION      TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    DN_USUARIO_MODIFICADOR BIGINT,
    DD_FECHA_MODIFICACION  TIMESTAMP,
    DN_ACTIVO              BOOLEAN       NOT NULL DEFAULT TRUE,
    CONSTRAINT FK_ORDEN_SUSCRIPCION FOREIGN KEY (FK_SUSCRIPCION) REFERENCES SUSCRIPCION (PK_ID) ON DELETE RESTRICT,
    CONSTRAINT FK_ORDEN_PLAN FOREIGN KEY (FK_PLAN) REFERENCES PLAN_SUSCRIPCION (PK_ID) ON DELETE RESTRICT,
    CONSTRAINT FK_ORDEN_SOLICITA FOREIGN KEY (FK_USUARIO_SOLICITA) REFERENCES USUARIO (PK_ID) ON DELETE RESTRICT,
    CONSTRAINT FK_ORDEN_VALIDA FOREIGN KEY (FK_USUARIO_VALIDA) REFERENCES USUARIO (PK_ID) ON DELETE RESTRICT,
    CONSTRAINT CK_ORDEN_PERIODO CHECK (TX_PERIODO IN ('MENSUAL', 'ANUAL')),
    CONSTRAINT CK_ORDEN_METODO CHECK (TX_METODO IN ('TARJETA', 'TRANSFERENCIA')),
    CONSTRAINT CK_ORDEN_ESTADO CHECK (TX_ESTADO IN ('PENDIENTE_PAGO', 'PROCESANDO', 'PAGADO', 'RECHAZADO', 'VENCIDO')),
    -- Algebra de la orden: Total = (Subtotal - Descuentos) + IVA
    CONSTRAINT CK_ORDEN_TOTAL CHECK (DN_TOTAL = DN_SUBTOTAL - DN_DESCUENTO + DN_IVA AND DN_TOTAL > 0),
    CONSTRAINT CK_ORDEN_PAGADA CHECK (TX_ESTADO <> 'PAGADO' OR DD_FECHA_PAGO IS NOT NULL)
);
CREATE UNIQUE INDEX IF NOT EXISTS UX_ORDEN_FOLIO ON ORDEN_PAGO (TX_FOLIO);
CREATE INDEX IF NOT EXISTS IX_ORDEN_ESTADO ON ORDEN_PAGO (TX_ESTADO, DD_FECHA_EXPIRACION) WHERE DN_ACTIVO;

-- Bitacora de webhooks recibidos: el ID del evento es unico, asi un aviso repetido
-- no cobra ni activa dos veces (idempotencia).
CREATE TABLE IF NOT EXISTS EVENTO_PAGO (
    PK_ID                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    TX_ID_EVENTO           VARCHAR(60)  NOT NULL,
    TX_TIPO                VARCHAR(40)  NOT NULL,
    FK_ORDEN               BIGINT,
    TX_RESULTADO           VARCHAR(20)  NOT NULL,
    DD_FECHA_RECIBIDO      TIMESTAMP    NOT NULL,
    DN_USUARIO_CREADOR     BIGINT       NOT NULL,
    DD_FECHA_CREACION      TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    DN_USUARIO_MODIFICADOR BIGINT,
    DD_FECHA_MODIFICACION  TIMESTAMP,
    DN_ACTIVO              BOOLEAN      NOT NULL DEFAULT TRUE,
    CONSTRAINT FK_EVENTO_ORDEN FOREIGN KEY (FK_ORDEN) REFERENCES ORDEN_PAGO (PK_ID) ON DELETE RESTRICT
);
CREATE UNIQUE INDEX IF NOT EXISTS UX_EVENTO_ID ON EVENTO_PAGO (TX_ID_EVENTO);

-- CFDI 4.0 simulado. Solo existe para ordenes PAGADAS y es inmutable: una
-- correccion seria una nota de credito, no un UPDATE.
CREATE TABLE IF NOT EXISTS FACTURA (
    PK_ID                       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    FK_ORDEN                    BIGINT        NOT NULL,
    TX_FOLIO_FISCAL             VARCHAR(36)   NOT NULL,
    TX_SERIE                    VARCHAR(10)   NOT NULL,
    TX_RFC_EMISOR               VARCHAR(13)   NOT NULL,
    TX_RAZON_SOCIAL_EMISOR      VARCHAR(300)  NOT NULL,
    TX_RFC_RECEPTOR             VARCHAR(13)   NOT NULL,
    TX_RAZON_SOCIAL_RECEPTOR    VARCHAR(300)  NOT NULL,
    TX_CODIGO_POSTAL_RECEPTOR   VARCHAR(5)    NOT NULL,
    TX_REGIMEN_FISCAL_RECEPTOR  VARCHAR(3)    NOT NULL,
    TX_USO_CFDI                 VARCHAR(4)    NOT NULL,
    TX_FORMA_PAGO               VARCHAR(2)    NOT NULL,
    DN_SUBTOTAL                 NUMERIC(10,2) NOT NULL,
    DN_DESCUENTO                NUMERIC(10,2) NOT NULL,
    DN_IVA                      NUMERIC(10,2) NOT NULL,
    DN_TOTAL                    NUMERIC(10,2) NOT NULL,
    DD_FECHA_TIMBRADO           TIMESTAMP     NOT NULL,
    TX_XML                      TEXT          NOT NULL,
    DN_USUARIO_CREADOR          BIGINT        NOT NULL,
    DD_FECHA_CREACION           TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    DN_USUARIO_MODIFICADOR      BIGINT,
    DD_FECHA_MODIFICACION       TIMESTAMP,
    DN_ACTIVO                   BOOLEAN       NOT NULL DEFAULT TRUE,
    CONSTRAINT FK_FACTURA_ORDEN FOREIGN KEY (FK_ORDEN) REFERENCES ORDEN_PAGO (PK_ID) ON DELETE RESTRICT
);
CREATE UNIQUE INDEX IF NOT EXISTS UX_FACTURA_ORDEN ON FACTURA (FK_ORDEN);
CREATE UNIQUE INDEX IF NOT EXISTS UX_FACTURA_FOLIO_FISCAL ON FACTURA (TX_FOLIO_FISCAL);
