-- Esquema del sistema de control de rutinas.
-- Fuente de verdad del modelo: Hibernate corre con ddl-auto: none.
--
-- Convenciones:
--   Tablas en MAYUSCULAS y singular.
--   Prefijos de columna: PK_ llave primaria, FK_ llave foranea, TX_ texto,
--   DN_ numerico o booleano, DD_ fecha.
--   Todas las tablas llevan auditoria y borrado logico (DN_ACTIVO).
--   La unicidad se aplica solo a registros activos (indice parcial).

CREATE TABLE IF NOT EXISTS AREA (
    PK_ID                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    TX_NOMBRE               VARCHAR(100) NOT NULL,
    TX_DESCRIPCION          VARCHAR(250),
    DN_USUARIO_CREADOR      BIGINT       NOT NULL,
    DD_FECHA_CREACION       TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    DN_USUARIO_MODIFICADOR  BIGINT,
    DD_FECHA_MODIFICACION   TIMESTAMP,
    DN_ACTIVO               BOOLEAN      NOT NULL DEFAULT TRUE
);

CREATE UNIQUE INDEX IF NOT EXISTS UQ_AREA_NOMBRE ON AREA (TX_NOMBRE) WHERE DN_ACTIVO;

-- Usuarios. Cumplimiento LFPDPPP: la contrasena se guarda solo como hash BCrypt
-- y no hay consentimiento sin fecha de consentimiento.
CREATE TABLE IF NOT EXISTS USUARIO (
    PK_ID                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    TX_NOMBRE               VARCHAR(150) NOT NULL,
    TX_CORREO               VARCHAR(150) NOT NULL,
    TX_HASH_CONTRASENA      VARCHAR(100) NOT NULL,
    TX_PERFIL               VARCHAR(20)  NOT NULL DEFAULT 'OPERADOR',
    DN_CONSENTIMIENTO_DATOS BOOLEAN      NOT NULL DEFAULT FALSE,
    DD_FECHA_CONSENTIMIENTO TIMESTAMP,
    DN_USUARIO_CREADOR      BIGINT       NOT NULL,
    DD_FECHA_CREACION       TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    DN_USUARIO_MODIFICADOR  BIGINT,
    DD_FECHA_MODIFICACION   TIMESTAMP,
    DN_ACTIVO               BOOLEAN      NOT NULL DEFAULT TRUE,
    CONSTRAINT CK_USUARIO_PERFIL CHECK (TX_PERFIL IN ('OPERADOR', 'SUPERVISOR', 'ADMINISTRADOR')),
    CONSTRAINT CK_USUARIO_CONSENTIMIENTO CHECK (NOT DN_CONSENTIMIENTO_DATOS OR DD_FECHA_CONSENTIMIENTO IS NOT NULL)
);

CREATE UNIQUE INDEX IF NOT EXISTS UQ_USUARIO_CORREO ON USUARIO (TX_CORREO) WHERE DN_ACTIVO;
